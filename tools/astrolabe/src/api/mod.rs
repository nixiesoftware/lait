#[derive(Debug, Clone, PartialEq)]
pub struct DiagnosisRow {
    pub gates: Vec<GateRow>,
    /// The first non-passing gate: the one actionable blocker.
    pub blocked_on: Option<String>,
    pub summary: String,
}

